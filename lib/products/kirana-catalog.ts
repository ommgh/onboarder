// Starter catalog for the "Loose" lane: unbranded staples a kirana weighs out by hand.
// A seller ticks what they stock, enters their rate per kg / litre / piece, picks pack
// sizes, and every pack becomes its own SKU grouped as variants on channels.

import type { Unit } from "./units";

export interface Pack {
  value: number;
  unit: Unit;
}

export interface LooseItem {
  key: string;
  name: string;
  hindi: string;
  group: string;
  ondcCategory: string;
  /** what the rate is quoted per */
  rateUnit: "kg" | "l" | "piece" | "dozen";
  packs: Pack[];
  defaultPacks: number[]; // indexes into packs selected by default
}

const g = (value: number): Pack => ({ value, unit: "g" });
const kg = (value: number): Pack => ({ value, unit: "kg" });
const ml = (value: number): Pack => ({ value, unit: "ml" });
const l = (value: number): Pack => ({ value, unit: "l" });
const pc = (value: number): Pack => ({ value, unit: "piece" });

const STAPLE = [g(500), kg(1), kg(2), kg(5), kg(10)];
const PULSE = [g(250), g(500), kg(1), kg(2)];
const SPICE = [g(50), g(100), g(250), g(500)];
const DRYFRUIT = [g(100), g(250), g(500), kg(1)];
const VEG = [g(250), g(500), kg(1), kg(2)];
const OIL = [ml(500), l(1), l(2), l(5)];

const item = (
  key: string,
  name: string,
  hindi: string,
  group: string,
  ondcCategory: string,
  rateUnit: LooseItem["rateUnit"],
  packs: Pack[],
  defaultPacks: number[],
): LooseItem => ({
  key,
  name,
  hindi,
  group,
  ondcCategory,
  rateUnit,
  packs,
  defaultPacks,
});

